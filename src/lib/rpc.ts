import { ErroDeNegocio } from '@/lib/resultado'

/** Erros que as funções SQL (migration 0007) levantam de propósito, traduzidos para o usuário. */
export function lancarErroRpc(error: { message: string }): never {
  const m = error.message
  if (m === 'item_nao_encontrado') throw new ErroDeNegocio('Item não encontrado')
  if (m === 'serie_nao_encontrada') throw new ErroDeNegocio('Série não encontrada')
  if (m === 'tag_nao_encontrada') throw new ErroDeNegocio('Tag não encontrada')
  if (m === 'apelido_nao_encontrado') throw new ErroDeNegocio('Não encontrei ninguém com esse apelido.')
  if (m === 'perfil_sem_apelido') throw new ErroDeNegocio('Defina o seu apelido em Configurações antes de adicionar amigos.')
  if (m === 'amizade_propria') throw new ErroDeNegocio('Você não pode adicionar a si mesmo.')
  if (m === 'amizade_existente') throw new ErroDeNegocio('Vocês já são amigos.')
  if (m === 'amizade_ja_solicitada') throw new ErroDeNegocio('Você já enviou um pedido para essa pessoa. Aguarde o aceite.')
  if (m === 'amizade_nao_encontrada') throw new ErroDeNegocio('Pedido de amizade não encontrado.')
  if (m === 'convite_invalido') throw new ErroDeNegocio('Este convite não vale mais (já foi usado ou expirou).')
  if (m === 'presente_ja_reservado') throw new ErroDeNegocio('Outro amigo já marcou este presente.')
  if (m === 'item_nao_possuido') throw new ErroDeNegocio('Só dá para emprestar um item que você tem.')
  if (m === 'emprestimo_em_aberto') throw new ErroDeNegocio('Este item já está emprestado. Marque a devolução antes de emprestar de novo.')
  if (m === 'emprestimo_nao_encontrado') throw new ErroDeNegocio('Empréstimo não encontrado ou já devolvido.')
  if (m === 'escopo_invalido') throw new ErroDeNegocio('Escolha ao menos uma seção para compartilhar.')
  if (m === 'sem_link_ativo') throw new ErroDeNegocio('Você não tem um link ativo.')
  if (m === 'capa_indisponivel') throw new ErroDeNegocio('Esta capa não está mais disponível.')
  if (m === 'contribuicao_nao_autorizada') throw new ErroDeNegocio('Ative "Contribuir com as capas que eu enviar" nas configurações para compartilhar fotos.')
  if (m === 'nada_a_marcar') throw new ErroDeNegocio('Esta série não tem volumes comprados para marcar como lidos.')
  if (m === 'variante_principal_nao_encontrado') throw new ErroDeNegocio('Volume normal não encontrado.')
  if (m === 'variante_de_variante') throw new ErroDeNegocio('Esse volume já é uma variante de outro. Escolha o volume normal.')
  if (m === 'variante_com_variantes') throw new ErroDeNegocio('Este volume já tem variantes; não pode ser variante de outro.')
  if (m.includes('itens_variante_nao_propria')) throw new ErroDeNegocio('Um volume não pode ser variante dele mesmo.')
  if (m === 'equivalencia_invalida') throw new ErroDeNegocio('Escolha uma obra diferente da sua para vincular.')
  if (m === 'equivalencia_obra_indisponivel') throw new ErroDeNegocio('Essa obra não está disponível: só dá para vincular a algo que um amigo seu compartilha.')
  if (m === 'equivalencia_limite') throw new ErroDeNegocio('Você já vinculou obras demais a este volume. Desfaça algum vínculo antes.')
  if (m === 'comentario_vazio') throw new ErroDeNegocio('Escreva alguma coisa para comentar.')
  if (m === 'comentario_longo') throw new ErroDeNegocio('O comentário passa de 500 caracteres.')
  if (m === 'comentario_nao_encontrado') throw new ErroDeNegocio('Comentário não encontrado.')
  if (m === 'item_nao_lido') throw new ErroDeNegocio('Só dá para registrar leitura de um volume marcado como lido.')
  if (m === 'leitura_em_variante') throw new ErroDeNegocio('As leituras ficam no volume normal; esta é uma variante dele.')
  if (m === 'favoritos_limite') throw new ErroDeNegocio('Você pode ter no máximo 4 favoritos. Tire um para escolher outro.')
  if (m === 'favoritos_repetido') throw new ErroDeNegocio('Esse favorito já está na sua lista.')
  if (m === 'favoritos_invalido') throw new ErroDeNegocio('Não entendi a lista de favoritos. Atualize a página e tente de novo.')
  if (m === 'item_nao_elegivel') throw new ErroDeNegocio('Esse volume não pode ser favorito: só vale volume único (sem série) que você tem na coleção.')
  if (m === 'lista_nao_encontrada') throw new ErroDeNegocio('Lista não encontrada.')
  if (m === 'lista_item_nao_encontrado') throw new ErroDeNegocio('Item da lista não encontrado.')
  if (m === 'lista_titulo_invalido') throw new ErroDeNegocio('O título da lista precisa ter de 1 a 80 caracteres.')
  if (m === 'lista_descricao_longa') throw new ErroDeNegocio('A descrição passa de 500 caracteres.')
  if (m === 'lista_tipo_invalido') throw new ErroDeNegocio('Tipo de lista inválido.')
  if (m === 'lista_nota_longa') throw new ErroDeNegocio('O comentário do item passa de 300 caracteres.')
  if (m === 'lista_limite') throw new ErroDeNegocio('Você chegou ao limite de 50 listas. Apague alguma para criar outra.')
  if (m === 'lista_cheia') throw new ErroDeNegocio('Esta lista já tem 200 itens.')
  if (m === 'lista_item_repetido') throw new ErroDeNegocio('Esta obra já está na lista.')
  if (m === 'lista_ordem_invalida') throw new ErroDeNegocio('A ordem mudou enquanto você editava. Recarregue a lista e tente de novo.')
  if (m === 'comentario_rapido') throw new ErroDeNegocio('Você está comentando rápido demais. Espere um minuto.')
  if (m === 'melhor_exige_lido') throw new ErroDeNegocio('Só dá para marcar como melhor da série um volume que você já leu.')
  if (m === 'melhor_exige_serie') throw new ErroDeNegocio('O volume precisa estar em uma série para ser o melhor dela.')
  if (m === 'melhor_em_variante') throw new ErroDeNegocio('A marca de melhor da série fica no volume normal; esta é uma variante dele.')
  if (m === 'melhor_exige_dois_lidos') throw new ErroDeNegocio('A série precisa ter ao menos 2 volumes lidos para escolher o melhor.')
  if (m === 'data_futura') throw new ErroDeNegocio('A leitura não pode ser no futuro.')
  if (m === 'lote_vazio') throw new ErroDeNegocio('Selecione ao menos um volume.')
  if (m === 'lote_grande') throw new ErroDeNegocio('São volumes demais de uma vez (o máximo é 100).')
  if (m === 'lote_repetido') throw new ErroDeNegocio('Um volume foi escolhido duas vezes.')
  if (m === 'lote_invalido') throw new ErroDeNegocio('Não entendi a lista de volumes. Tente de novo.')
  if (m === 'nota_invalida') throw new ErroDeNegocio('A nota vai de 0,5 a 5, de meia em meia estrela.')
  if (m === 'lote_item_indisponivel') throw new ErroDeNegocio('Um dos volumes já não está como comprado (talvez já tenha sido marcado como lido). Nada foi gravado: atualize a página e escolha de novo.')
  if (m === 'nao_autenticado') throw new ErroDeNegocio('Entre na sua conta para continuar.')
  if (m === 'critica_longa') throw new ErroDeNegocio('A crítica passa de 2000 caracteres.')
  if (m.startsWith('volumes_repetidos:')) {
    const numeros = m
      .slice('volumes_repetidos:'.length)
      .split(',')
      .map((n) => `#${Number(n)}`)
      .join(', ')
    throw new ErroDeNegocio(`Esta série já tem ${numeros} — desmarque ou renumere`)
  }
  throw new Error(m)
}
